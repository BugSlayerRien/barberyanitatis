  description TEXT,
  base_duration INT NOT NULL COMMENT 'Duration in minutes',
  base_price DECIMAL(10,2) NOT NULL,
  category ENUM('Haircut', 'Styling', 'Beard', 'Treatment') DEFAULT 'Haircut',
  is_active TINYINT(1) DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_category_active (category, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =========================
-- 5. AI SCAN SESSIONS (KIOSK ONLY)
-- =========================

CREATE TABLE kiosk_sessions (
  session_id VARCHAR(50) PRIMARY KEY COMMENT 'UUID generated by system',
  original_image_url VARCHAR(255),
  face_shape VARCHAR(50),
  hair_texture ENUM('Straight', 'Wavy', 'Curly', 'Coily'),
  hair_density ENUM('Thin', 'Medium', 'Thick'),
  scan_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  expires_at DATETIME NOT NULL COMMENT 'Session expires after 2 hours',
  is_processed TINYINT(1) DEFAULT 0,
  INDEX idx_expiry (expires_at, is_processed)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE kiosk_recommendations (
  recommendation_id INT AUTO_INCREMENT PRIMARY KEY,
  session_id VARCHAR(50) NOT NULL,
  variant_id INT NOT NULL,
  rank_position INT NOT NULL,
  match_score DECIMAL(4,3) NOT NULL COMMENT '0.000 to 1.000',
  is_selected TINYINT(1) DEFAULT 0,
  selected_view ENUM('Front', 'Side', 'Back') DEFAULT 'Front',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (session_id) REFERENCES kiosk_sessions(session_id) ON DELETE CASCADE,
  FOREIGN KEY (variant_id) REFERENCES hairstyle_variants(variant_id),
  UNIQUE KEY unique_session_rank (session_id, rank_position),
  INDEX idx_session_selected (session_id, is_selected)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =========================
-- 6. APPOINTMENTS (MOBILE APP)
-- =========================

CREATE TABLE appointments (
  appointment_id INT AUTO_INCREMENT PRIMARY KEY,
  booking_code VARCHAR(20) UNIQUE NOT NULL COMMENT 'Format: APP-YYYYMMDD-001',
  user_id INT NOT NULL,
  barber_id INT NOT NULL,
  appointment_date DATE NOT NULL,
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  status ENUM('Scheduled', 'CheckedIn', 'InProgress', 'Completed', 'Cancelled', 'NoShow') DEFAULT 'Scheduled',
  checkin_time DATETIME,
  completion_time DATETIME,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
