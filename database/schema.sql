  FOREIGN KEY (user_id) REFERENCES users(user_id),
  FOREIGN KEY (barber_id) REFERENCES barbers(barber_id),
  INDEX idx_date_status (appointment_date, status),
  INDEX idx_user_dates (user_id, appointment_date DESC)
