/* ====================================================================
  BARBERSHOP MANAGEMENT SYSTEM WITH AI HAIRSTYLE RECOMMENDATION
  Database Schema - MySQL
  Normalized to 3NF with proper relationships
   ==================================================================== */

-- =========================
-- 1. USER MANAGEMENT
-- =========================

CREATE TABLE users (
  user_id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(150) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(150) NOT NULL,
  phone VARCHAR(20),
  profile_image VARCHAR(255),
  gender ENUM('Male', 'Female', 'Other') DEFAULT 'Male',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  is_active TINYINT(1) DEFAULT 1,
  INDEX idx_email_active (email, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE user_profiles (
  profile_id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL UNIQUE,
  face_shape VARCHAR(50),
  hair_texture ENUM('Straight', 'Wavy', 'Curly', 'Coily'),
  hair_density ENUM('Thin', 'Medium', 'Thick'),
  hair_length ENUM('Short', 'Medium', 'Long'),
  last_scan_date DATE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
  INDEX idx_user_face_shape (user_id, face_shape)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE staff_users (
  staff_id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(150) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(150) NOT NULL,
  role ENUM('Admin', 'Receptionist') NOT NULL,
  is_active TINYINT(1) DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_staff_role_active (role, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =========================
-- 2. BARBER MANAGEMENT
-- =========================

CREATE TABLE barbers (
  barber_id INT AUTO_INCREMENT PRIMARY KEY,
  barber_code VARCHAR(10) UNIQUE NOT NULL,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(150) UNIQUE,
  password_hash VARCHAR(255),
  profile_image VARCHAR(255),
  specialty VARCHAR(100),
  years_experience INT,
  bio TEXT,
  rating DECIMAL(3,2) DEFAULT 5.00,
  is_active TINYINT(1) DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_code_active (barber_code, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =========================
-- 3. HAIRSTYLE CATALOG (AI DATASET)
-- =========================

CREATE TABLE hairstyles (
  hairstyle_id INT AUTO_INCREMENT PRIMARY KEY,
  style_code VARCHAR(20) UNIQUE NOT NULL,
  style_name VARCHAR(100) NOT NULL,
  description TEXT,
  gender ENUM('Male', 'Female', 'Unisex') DEFAULT 'Unisex',
  difficulty ENUM('Easy', 'Medium', 'Hard') DEFAULT 'Medium',
  maintenance ENUM('Low', 'Medium', 'High') DEFAULT 'Medium',
  popularity_score INT DEFAULT 0,
  is_active TINYINT(1) DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_gender_active (gender, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE hairstyle_variants (
  variant_id INT AUTO_INCREMENT PRIMARY KEY,
  hairstyle_id INT NOT NULL,
  face_shape VARCHAR(50) NOT NULL,
  hair_texture ENUM('Straight', 'Wavy', 'Curly', 'Coily') NOT NULL,
  front_view_url VARCHAR(255) NOT NULL,
  side_view_url VARCHAR(255),
  back_view_url VARCHAR(255),
  barber_instructions TEXT NOT NULL,
  clipper_sizes VARCHAR(100),
  styling_products TEXT,
  estimated_minutes INT DEFAULT 30,
  confidence_score DECIMAL(4,3) DEFAULT 0.8,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (hairstyle_id) REFERENCES hairstyles(hairstyle_id) ON DELETE CASCADE,
  UNIQUE KEY unique_variant (hairstyle_id, face_shape, hair_texture),
  INDEX idx_face_hair (face_shape, hair_texture)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- =========================
-- 4. SERVICES & PRICING
-- =========================

CREATE TABLE services (
  service_id INT AUTO_INCREMENT PRIMARY KEY,
  service_code VARCHAR(20) UNIQUE NOT NULL,
